#!/usr/bin/env python3
"""The kept pairs, deduped and stripped, as the evaluator sweep's input.

    python tools/build_eval_dataset.py --run data/my_run
    python tools/build_eval_dataset.py --run data/my_run --pool all

**Two files out, and the split is the point.** `eval_dataset.json` is what an evaluator is
shown; `eval_answers.json` is the label and everything that implies it. They are joined by
`id` at scoring time (`metaeval.scoring.attach_answers`).

The split is not cosmetic. `levels` is **slot-ordered** -- `levels[0]` is `response_1`'s
steering level -- so a file carrying `levels`, `positive_hint`, `negative_hint` and
`correct_response` beside the two responses hands the answer to anyone who reads it. That is
harmless while the only consumer is our own scorer, which never puts those fields in a prompt,
and not harmless at all once the dataset is published: the first thing a third party does with
a benchmark is feed the whole record to a model.

**Do not point `run_evaluators.py --dataset` at a run's `dataset.json`.** That file is every
*draw*, which is right for the filter's denominator and wrong as an evaluation set, for two
reasons that both cost real money at 1,000 pairs:

- **It is 1,673 pairs where 1,000 were kept.** A re-draw happens only because the filter
  rejected the previous one, so scoring all of them spends 67% extra to score pairs the
  pipeline decided not to ship. `run_pipeline.Store.write_dataset` says so in its docstring;
  nothing until now did the dedupe it asks for.
- **It is 663MB, and 1.9GB once parsed**, because every pair embeds both trajectories in
  full. The evaluator reads seven fields and none of them is a trajectory.

Both are fixed here: `pair_index.json` names the winning draw per cell, and the per-pair files
are read one at a time so the 663MB is never held at once. Output is ~1.5% of the input.

**What is dropped, and why that is safe.** `trajectory_1` / `trajectory_2` and the bulk of
`context` -- its `policy`, `agent_tools`, `knowledge_base` and the other rendering inputs. The
evaluator never sees them: `prompt` already carries the rendered policy and tool list, which
is exactly what the human annotators were shown, and that parity is why the
design. `context.domain` and `context.task_id` stay on the blind record, and `levels` / `group_id`
move to the answers file, because a per-slice reading of the results needs to partition on
them. The file is
derived, so anything pruned by mistake is one re-run away.

**One field is added rather than copied: `agent`**, the model that generated the pair, lifted
out of the trajectory provenance before the trajectory goes. Three models in the evaluator
roster -- `gpt-oss-20b`, `gpt-oss-120b`, `nemotron-lightning` -- are also the agents that
produced these conversations, so "does an evaluator prefer its own output" is a real question
about this benchmark, and it is unanswerable once the trajectories are gone. See `agent_of`.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

# What the evaluator is shown: the prompt, the two responses, the criterion, and an id to
# join on. Nothing here implies which side is better.
BLIND = ("id", "criterion_name", "criterion_description",
         "prompt", "response_1", "response_2", "schema_version")

# The label and everything that reveals it. `levels` is slot-ordered, so it is a label;
# the two hints are the steering text, which names its own direction. `group_id` and `agent`
# are neither -- they are provenance -- but they belong with the answers because the scorer
# does not read them either, and a second file is one file to keep out of a prompt.
ANSWER = ("id", "correct_response", "levels", "positive_hint", "negative_hint", "group_id")
# Both trajectories of a pair are generated by the same agent, so one string per pair.
AGENT_SUFFIXES = ("gpt-oss-120b", "gpt-oss-20b", "nemotron-lightning-3p5-30b-a3b")
# `context` is 20KB of which 19KB is the policy and tool list the `prompt` already renders.
KEEP_CONTEXT = ("domain", "task_id", "task_purpose", "user_persona")


def _pair_file(pairs_dir: Path, key: str, attempt: int) -> Path:
    """The file holding one cell's draw. Attempt 1 has no infix; see `Store._attempt_suffix`."""
    suffix = "" if attempt <= 1 else f".a{attempt}"
    return pairs_dir / f"{key}{suffix}.pairs.json"


def agent_of(pair: dict) -> str:
    """Which model generated this pair's trajectories, as a bare name.

    **Lifted out of the trajectory before the trajectory is dropped**, because it is the only
    way a downstream report can measure self-preference: three of the evaluators in the roster
    are also the agents that produced these conversations, and "does an evaluator score its own
    output higher" is answerable only if each pair remembers who wrote it.

    Read from `trajectory_1.provenance.agent_model` -- both sides of a pair come from the same
    agent, which is what makes the steering contrast a property of the hints rather than of the
    model. Returns "" when provenance is missing, so a report can say "unknown" instead of
    silently attributing the pair to nobody.
    """
    for side in ("trajectory_1", "trajectory_2"):
        model = ((pair.get(side) or {}).get("provenance") or {}).get("agent_model") or ""
        if model:
            return model.rsplit("/", 1)[-1]
    return ""


def blind(pair: dict) -> dict:
    """The record an evaluator may see. Context is the four fields that identify the task."""
    out = {k: pair[k] for k in BLIND if k in pair}
    ctx = pair.get("context") or {}
    out["context"] = {k: ctx[k] for k in KEEP_CONTEXT if k in ctx}
    return out


def answer(pair: dict) -> dict:
    """The label side of the same record, joined back by `id`."""
    out = {k: pair[k] for k in ANSWER if k in pair}
    out["agent"] = agent_of(pair)
    return out


def build(run: Path, pool: str = "kept") -> tuple[list[dict], list[dict], list[str]]:
    """`(blind, answers, problems)` -- the winning draw of every selected cell, split in two.

    Ordered by cell key rather than by file-system order, so the same run directory always
    yields the same file. That matters more than it looks: `run_evaluators.py --limit N`
    takes a prefix, and a prefix of an unstable order is not a reproducible smoke test.
    """
    index = json.loads((run / "pair_index.json").read_text())
    pairs_dir = run / "pairs"
    entries, answers, problems = [], [], []
    for key in sorted(index):
        cell = index[key]
        if pool == "kept" and cell.get("state") != "kept":
            continue
        pair_id, attempt = cell.get("pair_id"), cell.get("attempt", 1)
        if not pair_id:
            problems.append(f"{key}: state={cell.get('state')} but no pair_id")
            continue
        f = _pair_file(pairs_dir, key, attempt)
        if not f.is_file():
            problems.append(f"{key}: {f.name} missing")
            continue
        try:
            records = json.loads(f.read_text())
        except (json.JSONDecodeError, OSError) as e:
            problems.append(f"{key}: {f.name} unreadable ({type(e).__name__})")
            continue
        # Matched by id, not by position. A file can hold more than one record, and the index
        # names *which* draw won -- taking `records[0]` would silently score a rejected one.
        hit = next((r for r in records if r.get("id") == pair_id), None)
        if hit is None:
            problems.append(f"{key}: pair {pair_id[:8]} not in {f.name}")
            continue
        entries.append(blind(hit))
        answers.append(answer(hit))
    return entries, answers, problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--run", type=Path, required=True,
                    help="a run directory holding pair_index.json and pairs/")
    ap.add_argument("--out", type=Path, default=None,
                    help="default: <run>/eval_dataset.json. The answers go beside it as "
                         "<stem>_answers.json -- eval_answers.json by default.")
    ap.add_argument("--pool", default="kept", choices=("kept", "all"),
                    help="'kept' (default) is the shipped benchmark: the winning draw of "
                         "every cell the filter accepted. 'all' adds the rejected cells' "
                         "winning draws, for measuring the filter rather than the data.")
    a = ap.parse_args()

    entries, answers, problems = build(a.run, a.pool)
    out = a.out or (a.run / "eval_dataset.json")
    # `eval_dataset.json` -> `eval_answers.json`; any other stem gets `_answers` appended, so
    # the pair is always discoverable from either name alone.
    ans = (out.with_name("eval_answers.json") if out.name == "eval_dataset.json"
           else out.with_name(f"{out.stem}_answers{out.suffix}"))
    out.write_text(json.dumps(entries, indent=2))
    ans.write_text(json.dumps(answers, indent=2))

    src = a.run / "dataset.json"
    n_all = 0
    if src.is_file():
        n_all = src.stat().st_size
    print(f"{len(entries):,} pair(s) from --pool {a.pool} -> {out}")
    print(f"  labels -> {ans} ({ans.stat().st_size / 1e6:.1f} MB)")
    print(f"  {out.stat().st_size / 1e6:.1f} MB"
          + (f", from {n_all / 1e6:.0f} MB of dataset.json "
             f"({out.stat().st_size / n_all:.1%})" if n_all else ""))
    import collections
    by = collections.Counter((e["context"].get("domain"), e["criterion_name"])
                             for e in entries)
    print(f"  {len({d for d, _ in by})} domain(s) x {len({c for _, c in by})} criterion "
          f"= {len(by)} cell(s), {min(by.values())}-{max(by.values())} pairs each")
    # **Loud, and non-fatal.** A missing pair file is a real gap in the benchmark and the
    # count of pairs is a number the paper quotes, so it cannot be discovered later from a
    # total that looks plausible. But 999 good pairs still beat refusing to write anything.
    if problems:
        print(f"\n  {len(problems)} cell(s) could not be read:")
        for p in problems[:20]:
            print(f"    {p}")
        if len(problems) > 20:
            print(f"    ... and {len(problems) - 20} more")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
